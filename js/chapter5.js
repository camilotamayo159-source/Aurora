let razonActual = 0;

/*=========================================
        MOSTRAR RAZÓN
=========================================*/

function mostrarRazon(){

    const razon=razones[razonActual];

    const card=document.getElementById("reasonCard");

    card.classList.remove("card-in");

    card.classList.add("card-out");

    setTimeout(()=>{

        document
        .getElementById("reasonCounter")
        .textContent=`${razon.numero} de 100`;

        document
        .getElementById("reasonText")
        .textContent=razon.texto;

        ejecutarEfecto(razon.efecto);

        card.classList.remove("card-out");

        card.classList.add("card-in");

    },350);

}

/*=========================================
        SIGUIENTE RAZÓN
=========================================*/

function siguienteRazon(){

    const boton=document.getElementById("nextReason");

    boton.disabled=true;

    boton.classList.add("button-click");

    setTimeout(()=>{

        boton.classList.remove("button-click");

        // Si la siguiente sería la razón 100,
        // saltamos directamente a la escena final.
        if(razonActual==98){

            escenaFinal100();
            return;

        }

        razonActual++;

        mostrarRazon();

        boton.disabled=false;

    },220);

}

