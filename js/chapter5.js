function crearEstrellas(){

    for(let i=0;i<20;i++){

        const estrella=document.createElement("div");

        estrella.className="star";

        estrella.textContent="✨";

        estrella.style.left=Math.random()*window.innerWidth+"px";

        estrella.style.top=(window.innerHeight-150)+Math.random()*120+"px";

        estrella.style.animationDelay=(Math.random()*.4)+"s";

        document.body.appendChild(estrella);

        setTimeout(()=>{

            estrella.remove();

        },2800);

    }

}

function crearEstrellas(){

    const corazon=document.querySelector(".reason-heart");

    for(let i=0;i<10;i++){

        const estrella=document.createElement("span");

        estrella.className="heart-star";

        estrella.textContent="✨";

        const angulo=Math.random()*360;

        const distancia=40+Math.random()*45;

        const x=Math.cos(angulo*Math.PI/180)*distancia;

        const y=Math.sin(angulo*Math.PI/180)*distancia;

        estrella.style.setProperty("--x",`${x}px`);

        estrella.style.setProperty("--y",`${y}px`);

        estrella.style.left="50%";

        estrella.style.top="50%";

        corazon.appendChild(estrella);

        setTimeout(()=>{

            estrella.remove();

        },1800);

    }

}

